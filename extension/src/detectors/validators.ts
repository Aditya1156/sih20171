export function verhoeffCheck(num: string): boolean {
  const digits = num.replace(/\D/g, '');
  if (digits.length !== 12) return false;

  let c = 0;
  const len = digits.length;
  for (let i = 0; i < len; i++) {
    c = VERHOEFF_D[c][VERHOEFF_P[(i + 1) % 8][parseInt(digits[len - 1 - i], 10)]];
  }
  return c === 0;
}

export function isValidPAN(pan: string): boolean {
  return /^[A-Z]{5}[0-9]{4}[A-Z]$/.test(pan.trim());
}

export function isValidIFSC(ifsc: string): boolean {
  return /^[A-Z]{4}0[A-Z0-9]{6}$/.test(ifsc.trim());
}

export function isValidUPI(upi: string): boolean {
  return /^[a-zA-Z0-9._-]+@[a-zA-Z]{2,}$/.test(upi.trim());
}

export function isValidEmail(email: string): boolean {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email.trim());
}

export function isValidIndianPhone(phone: string): boolean {
  const digits = phone.replace(/[\s().-]/g, '').replace(/-/g, '');
  return /^(?:\+?91|0)?[6-9]\d{9}$/.test(digits);
}
